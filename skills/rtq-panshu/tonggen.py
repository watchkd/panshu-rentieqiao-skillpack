"""通根查表工具 v2 —— 任铁樵《滴天髓阐微》口径的机械通根判定。

【修正 v2 要点】：
  1. 采「阳干顺行、阴干逆行」标准十二长生（通行子平），不再五行一刀切，
     以消除"辛金在巳"（阴死地）被误判长生的硬伤。
  2. 根力分两级：重根（长生禄旺）、轻根（墓库/中气/余气）。
  3. 任氏实证标定（命例库 145 条通根断语）：
     · 禄支/长生/本气/中气/墓库 皆可作根（有根）——例 LQ-06-007 癸通根禄支子、
       LQ-07-006 戌月通根身库、LQ-25-007 丑中藏辛为庚根(助忌则深)。
     · "余气/虚脱/且被冲穿" 常不足以为根——例 LQ-06-001 戊土余气不算根、
       LQ-06-006 丁火中气被冲丑未则虚脱。
   故表输出两级根力，是否算"有效根"再交语境（该支被冲穿否、是否忌神得根）决断。

输出 tonggen(gan, zhi) → {"档":"重|轻|无", "性":"长生|禄|旺|墓库|本气|中气|余气|无"}
只定性两级，不量化打分（不度日主旺衰百分比）。
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(HERE, "skills", "rtq-panshu", "数据")
OUT_JSON = os.path.join(DATA_DIR, "通根查表.json")

WX = {"甲": "木", "乙": "木", "丙": "火", "丁": "火", "戊": "土",
      "己": "土", "庚": "金", "辛": "金", "壬": "水", "癸": "水"}

CANG = {
    "子": ["癸"], "丑": ["己", "癸", "辛"],
    "寅": ["甲", "丙", "戊"], "卯": ["乙"],
    "辰": ["戊", "乙", "癸"], "巳": ["丙", "庚", "戊"],
    "午": ["丁", "己"], "未": ["己", "丁", "乙"],
    "申": ["庚", "壬", "戊"], "酉": ["辛"],
    "戌": ["戊", "辛", "丁"], "亥": ["壬", "甲"],
}

# 十二长生（标准十二地支长生/禄/旺，阳干顺、阴干逆）
# 长生/禄/旺：某干之间
CS_LU_WANG = {
    # 阳干
    "甲": ("亥", "寅", "卯"),
    "丙": ("寅", "巳", "午"),
    "戊": ("寅", "巳", "午"),
    "庚": ("巳", "申", "酉"),
    "壬": ("申", "亥", "子"),
    # 阴干（逆行：长生在对冲性质位）
    "乙": ("午", "卯", "寅"),   # 乙长生在午（逆），禄在卯日主
    "丁": ("酉", "午", "巳"),
    "己": ("酉", "午", "巳"),
    "辛": ("子", "酉", "申"),
    "癸": ("卯", "子", "亥"),
}
# 注：乙禄卯、癸禄子是通行（阴干禄与其刃同），故乙禄卯、癸禄子正确。
# 乙旺=寅(阳刃)、癸旺=亥。此处旺取"帝旺逆行即阳刃前一位"，按通行"乙帝旺在寅/癸帝旺在亥"。

# 墓库（任氏 TS-17-04 明文：甲乙未、丙丁戌、庚辛丑、壬癸辰；土四库自根）
MU = {"木": "未", "火": "戌", "金": "丑", "水": "辰", "土": None}
GAMU = {"甲": "未", "乙": "未", "丙": "戌", "丁": "戌", "戊": "辰", "己": "丑",
        "庚": "丑", "辛": "丑", "壬": "辰", "癸": "辰"}

def tonggen(gan, zhi):
    cang = CANG[zhi]
    # 重：长生禄旺
    if zhi in CS_LU_WANG[gan]:
        cs, lu, wang = CS_LU_WANG[gan]
        prop = "长生" if zhi == cs else ("禄" if zhi == lu else "旺")
        return {"档": "重", "性": prop, "五行": WX[gan]}
    # 墓库
    if zhi == GAMU[gan]:
        return {"档": "轻", "性": "墓库", "五行": WX[gan]}
    # 本气/中气/余气（藏干同五行）
    for name, g in zip(("本气", "中气", "余气"), cang):
        if WX[g] == WX[gan]:
            if name == "本气":
                return {"档": "轻", "性": "本气", "五行": WX[gan]}
            return {"档": "轻", "性": name, "五行": WX[gan]}
    return {"档": "无", "性": "无", "五行": WX[gan]}

def build():
    return {g + z: tonggen(g, z) for g in "甲乙丙丁戊己庚辛壬癸" for z in "子丑寅卯辰巳午未申酉戌亥"}

